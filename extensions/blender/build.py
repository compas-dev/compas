"""Build the COMPAS Blender extension.

Blender extensions must be self-contained: all third-party Python packages are
bundled as wheels inside the extension ``.zip``. Blender LTS releases ship different
Python versions, so one set of packages is built per Python version, each one
limited to the Blender versions that use that Python version, and split per platform.

Usage::

    python extensions/blender/build.py
    python extensions/blender/build.py --blender /path/to/blender --python 3.13

The resulting ``.zip`` files are written to ``dist/blender`` and can be installed
in Blender via *Edit > Preferences > Get Extensions > Install from Disk...*.

Requires ``pip`` in the current environment and a Blender executable (4.2 or newer)
to run ``blender --command extension build``.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ADDON_DIR = HERE / "addon"
REQUIREMENTS = ROOT / "requirements.txt"
DEFAULT_OUTPUT = ROOT / "dist" / "blender"

# Packages that Blender already ships with its own Python and therefore must not be bundled.
PROVIDED_BY_BLENDER = {"numpy"}

LINUX_X64 = ["manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64"]

# One build per Python version used by Blender.
# ``blender_max`` is exclusive (the first version that is *not* supported).
# Platform tags are passed to ``pip download --platform``; pip expands macOS tags to
# older macOS versions automatically, but manylinux tags have to be listed explicitly.
TARGETS = {
    "3.11": {
        "blender_min": "4.2.0",
        "blender_max": "5.1.0",
        "platforms": {
            "windows-x64": ["win_amd64"],
            "macos-arm64": ["macosx_12_0_arm64"],
            "macos-x64": ["macosx_11_0_x86_64"],
            "linux-x64": LINUX_X64,
        },
    },
    "3.13": {
        "blender_min": "5.1.0",
        "blender_max": None,
        "platforms": {
            "windows-x64": ["win_amd64"],
            "windows-arm64": ["win_arm64"],
            "macos-arm64": ["macosx_12_0_arm64"],
            "linux-x64": LINUX_X64,
        },
    },
}

ALL_PLATFORMS = sorted({platform for target in TARGETS.values() for platform in target["platforms"]})


def log(message):
    print(message, flush=True)


def run(cmd, **kwargs):
    log("  $ " + " ".join(str(c) for c in cmd))
    return subprocess.run([str(c) for c in cmd], check=True, **kwargs)


def find_blender(explicit=None):
    candidates = [explicit, os.environ.get("BLENDER"), shutil.which("blender")]
    if sys.platform == "darwin":
        candidates.append("/Applications/Blender.app/Contents/MacOS/Blender")
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return candidate
    raise SystemExit("Blender executable not found. Pass --blender or set the BLENDER environment variable.")


def compas_version():
    content = (ROOT / "src" / "compas" / "__init__.py").read_text(encoding="utf-8")
    return re.search(r'^__version__ = "([^"]+)"', content, re.M).group(1)


def distribution_name(wheel):
    return wheel.name.split("-")[0].lower().replace("_", "-")


def build_compas_wheel(dest, version, from_pypi):
    dest.mkdir(parents=True, exist_ok=True)
    if from_pypi:
        run([sys.executable, "-m", "pip", "download", "compas=={}".format(version), "--no-deps", "--only-binary=:all:", "--dest", dest, "--quiet"])
    else:
        run([sys.executable, "-m", "pip", "wheel", ROOT, "--no-deps", "--wheel-dir", dest, "--quiet"])
    wheels = list(dest.glob("compas-*.whl"))
    if len(wheels) != 1:
        raise SystemExit("Expected exactly one compas wheel in {}, found: {}".format(dest, wheels))
    return wheels[0]


def download_dependencies(dest, python_version, platform_tags):
    cmd = [sys.executable, "-m", "pip", "download", "-r", REQUIREMENTS, "--only-binary=:all:"]
    cmd += ["--python-version", python_version, "--implementation", "cp", "--dest", dest, "--quiet"]
    for tag in platform_tags:
        cmd += ["--platform", tag]
    try:
        run(cmd)
    except subprocess.CalledProcessError:
        return False
    return True


def write_manifest(source, target, version, blender_min, blender_max, platforms, wheels):
    content = source.read_text(encoding="utf-8")
    content = re.sub(r'^version = ".*"$', 'version = "{}"'.format(version), content, flags=re.M)
    content = re.sub(r'^blender_version_min = ".*"$', 'blender_version_min = "{}"'.format(blender_min), content, flags=re.M)

    lines = ["", "# Generated by extensions/blender/build.py"]
    if blender_max:
        lines.append('blender_version_max = "{}"'.format(blender_max))
    lines.append("platforms = [{}]".format(", ".join('"{}"'.format(p) for p in platforms)))
    lines.append("wheels = [")
    lines += ['  "./wheels/{}",'.format(wheel.name) for wheel in wheels]
    lines.append("]")
    target.write_text(content.rstrip() + "\n" + "\n".join(lines) + "\n", encoding="utf-8")


def build_target(blender, python_version, target, compas_wheel, version, output_dir, work_dir, only_platforms=None):
    tag = "py" + python_version.replace(".", "")
    blender_min_short = ".".join(target["blender_min"].split(".")[:2])
    log("\nBuilding for Python {} (Blender {}{})".format(python_version, target["blender_min"], " to < " + target["blender_max"] if target["blender_max"] else "+"))

    staging = work_dir / tag / "compas"
    if staging.exists():
        shutil.rmtree(staging)
    wheels_dir = staging / "wheels"
    wheels_dir.mkdir(parents=True)

    shutil.copy2(ADDON_DIR / "__init__.py", staging / "__init__.py")
    shutil.copy2(compas_wheel, wheels_dir / compas_wheel.name)

    platforms = []
    for platform, platform_tags in target["platforms"].items():
        if only_platforms and platform not in only_platforms:
            continue
        log("- {}".format(platform))
        if download_dependencies(wheels_dir, python_version, platform_tags):
            platforms.append(platform)
        else:
            log("  WARNING: dependencies not available for {} on Python {}, skipping this platform.".format(platform, python_version))

    if not platforms:
        raise SystemExit("No platform could be built for Python {}.".format(python_version))

    for wheel in list(wheels_dir.glob("*.whl")):
        if distribution_name(wheel) in PROVIDED_BY_BLENDER:
            wheel.unlink()

    wheels = sorted(wheels_dir.glob("*.whl"))
    write_manifest(ADDON_DIR / "blender_manifest.toml", staging / "blender_manifest.toml", version, target["blender_min"], target["blender_max"], platforms, wheels)

    build_output = work_dir / tag / "out"
    if build_output.exists():
        shutil.rmtree(build_output)
    build_output.mkdir(parents=True)
    run([blender, "--factory-startup", "--command", "extension", "build", "--split-platforms", "--source-dir", staging, "--output-dir", build_output])

    results = []
    for package in sorted(build_output.glob("*.zip")):
        # compas-2.15.0-macos_arm64.zip -> compas-2.15.0-blender4.2-macos_arm64.zip
        name = package.name.replace("compas-{}-".format(version), "compas-{}-blender{}-".format(version, blender_min_short))
        target_path = output_dir / name
        shutil.move(str(package), str(target_path))
        results.append(target_path)
    return results


def main():
    parser = argparse.ArgumentParser(description="Build the COMPAS Blender extension.")
    parser.add_argument("--blender", help="Path to the Blender executable (defaults to $BLENDER, then PATH).")
    parser.add_argument("--python", choices=sorted(TARGETS), action="append", help="Only build for these Blender Python versions (default: all).")
    parser.add_argument("--platform", choices=ALL_PLATFORMS, action="append", help="Only build for these platforms (default: all).")
    parser.add_argument("--output-dir", default=str(DEFAULT_OUTPUT), help="Output folder for the extension packages.")
    parser.add_argument("--from-pypi", action="store_true", help="Bundle the released compas wheel from PyPI instead of building it from this checkout.")
    args = parser.parse_args()

    blender = find_blender(args.blender)
    version = compas_version()
    output_dir = Path(args.output_dir).resolve()
    work_dir = output_dir / "build"
    output_dir.mkdir(parents=True, exist_ok=True)
    for old in output_dir.glob("compas-*.zip"):
        old.unlink()

    log("Building COMPAS {} wheel".format(version))
    compas_wheel = build_compas_wheel(work_dir / "compas_wheel", version, args.from_pypi)

    packages = []
    for python_version in args.python or sorted(TARGETS):
        target = TARGETS[python_version]
        if args.platform and not set(args.platform) & set(target["platforms"]):
            log("\nSkipping Python {}: none of {} supported.".format(python_version, ", ".join(args.platform)))
            continue
        packages += build_target(blender, python_version, target, compas_wheel, version, output_dir, work_dir, args.platform)

    if not packages:
        raise SystemExit("Nothing was built.")

    shutil.rmtree(work_dir, ignore_errors=True)

    log("\nExtension packages:")
    for package in packages:
        log("  {} ({:.1f} MB)".format(package, package.stat().st_size / 1e6))


if __name__ == "__main__":
    main()
